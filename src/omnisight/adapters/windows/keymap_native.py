"""Windows 原生位置码 → HID usage → ``key_id``（04 文档 §3.2、§3.5）。

**以扫描码而非虚拟键码为枢轴**，这是相对 KeyTrace 的实质改动，理由有两条：

1. 热力图的语义是"你的手指落在哪个物理键上"。扫描码就是物理位置；虚拟键码会随
   键盘布局变化（德语键盘上 ``scan 0x1A`` 报 ``VK_OEM_1``，美式报 ``VK_OEM_4``），
   用它当身份会让同一个物理键在不同布局下算成两个键。
2. KeyTrace 为了修正 VK 的歧义写了四处特殊处理（左右 Shift 靠扫描码、左右 Ctrl/Alt
   靠扩展位、小键盘导航簇靠 ``NUMPAD_BY_SCAN``、小键盘回车靠扩展位）。改用
   ``(扫描码, E0)`` 作键之后，这四处**全部消失**——它们本来就是同一个信息的四种
   绕法。下面表里 ``0x2A``/``0x36``、``0x1D``/``E0 0x1D``、``0x4B``/``E0 0x4B``、
   ``0x1C``/``E0 0x1C`` 天然是不同的条目。

扫描码无法区分的只剩一处：**Pause 与 NumLock**。Pause 走 ``E1 1D`` + ``45`` 两段，
第二段的 MakeCode 恰好是 NumLock 的 ``0x45``。因此保留一处 VK 判定作为例外，
并把 ``E1`` 前缀段丢弃——它不是一次按键。
"""

from __future__ import annotations

from ..hid import key_id_for_hid


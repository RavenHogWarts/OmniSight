#: 带 ``E0`` 前缀的扩展扫描码 → HID usage。
#:
#: 这张表是"小键盘导航簇"歧义的真正解法：NumLock 关闭时小键盘 4 会上报
#: ``VK_LEFT``，但它的扫描码始终是 ``0x4B`` 且**不带** E0；真正的方向键左带 E0。
#: 两组物理键因此自然分开，不需要 KeyTrace 那张 ``NUMPAD_BY_SCAN`` 修正表。
EXTENDED_SCAN_TO_HID: dict[int, int] = {
    0x1C: 0x58,  # 小键盘 Enter
    0x1D: 0xE4,  # 右 Ctrl
    0x35: 0x54,  # 小键盘 /
    0x37: 0x46,  # PrtSc
    0x38: 0xE6,  # 右 Alt（AltGr）
    0x46: 0x48,  # Ctrl+Break，与 Pause 同一物理键
    0x47: 0x4A,  # Home
    0x48: 0x52,  # ↑
    0x49: 0x4B,  # PgUp
    0x4B: 0x50,  # ←
    0x4D: 0x4F,  # →
    0x4F: 0x4D,  # End
    0x50: 0x51,  # ↓
    0x51: 0x4E,  # PgDn
    0x52: 0x49,  # Insert
    0x53: 0x4C,  # Delete
    0x5B: 0xE3,  # 左 Win
    0x5C: 0xE7,  # 右 Win
    0x5D: 0x65,  # 菜单键
}

#: 扫描码查不到时的兜底：少数键盘/虚拟设备只填 VKey 而把 MakeCode 报成 0。
#: 刻意只收录**位置无歧义**的键——修饰键与小键盘不在其中，因为它们正是需要靠
#: 扫描码区分左右的那些。
VK_FALLBACK_TO_HID: dict[int, int] = {
    0x08: 0x2A,  # VK_BACK
    0x09: 0x2B,  # VK_TAB
    0x0D: 0x28,  # VK_RETURN → 主键盘 Enter
    0x14: 0x39,  # VK_CAPITAL
    0x1B: 0x29,  # VK_ESCAPE
    0x20: 0x2C,  # VK_SPACE
    0x21: 0x4B, 0x22: 0x4E, 0x23: 0x4D, 0x24: 0x4A,
    0x25: 0x50, 0x26: 0x52, 0x27: 0x4F, 0x28: 0x51,
    0x2C: 0x46,  # VK_SNAPSHOT
    0x2D: 0x49, 0x2E: 0x4C,
    0x90: 0x53,  # VK_NUMLOCK
    0x91: 0x47,  # VK_SCROLL
    **{0x30 + index: 0x27 if index == 0 else 0x1D + index for index in range(10)},
    **{0x41 + index: 0x04 + index for index in range(26)},
    **{0x70 + index: 0x3A + index for index in range(12)},
}


def resolve(vk: int, scan: int, flags: int) -> tuple[str | None, int | None, bool]:
    """把一次 Raw Input 上报解析为 ``(key_id, hid_usage, is_down)``。

    纯函数、无副作用，因此可以用录制的原生事件做表驱动测试（11 文档 §8.1）——
    这是"Linux 适配器能在 Windows 开发机上被测"的同一机制。

    ``key_id`` 为 ``None`` 有两种情况，调用方都应计入"未映射"计数而不是静默忽略：
    收到了 Pause 的 ``E1`` 前缀段（不是按键），或该键确实不在表内（媒体键、
    厂商自定义键）。
    """
    is_down = not bool(flags & RI_KEY_BREAK)
    extended = bool(flags & RI_KEY_E0)
    prefix = bool(flags & RI_KEY_E1)

    # Pause 的报文是 E1 1D + 45 两段。第一段是前缀而非按键，必须丢弃——否则每按一次
    # Pause 都会多记一次左 Ctrl。
    if prefix and scan == 0x1D:
        return None, None, is_down
    # 第二段的 MakeCode 与 NumLock 撞车，是全表唯一必须靠 VK 消歧的地方。
    if vk == VK_PAUSE:
        return key_id_for_hid(0x48), 0x48, is_down

    table = EXTENDED_SCAN_TO_HID if extended else SCAN_TO_HID
    usage = table.get(scan)
    if usage is None:
        usage = VK_FALLBACK_TO_HID.get(vk)
    return key_id_for_hid(usage), usage, is_down


